"""Builds the white "NexaGram" wordmark vectors that replace Telegram's text logos.

Telegram tints these drawables with the theme color, so they must stay white.
Output goes to TMessagesProj_App/src/main/res/drawable (overrides Telegram's files
without touching them). Font: Roboto (Apache 2.0) bundled with the app.

usage: python make_wordmark.py <font.ttf> <res/drawable-anydpi-v24 dir>

Must go to drawable-anydpi-v24: Telegram ships its logos pre-split into that
folder, and a plain drawable/ would lose to it on Android 7+.
"""
import os
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

TEXT = "NexaGram"
FONT, OUT = sys.argv[1], sys.argv[2]

# name, viewport w, viewport h, width dp, height dp — same proportions as Telegram's originals
TARGETS = [
    ("telegram_logo", 249, 57, "83dp", "19dp"),
    ("telegram_logo_2", 269, 61, "90dp", "20.408922dp"),
]

font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
hmtx = font["hmtx"]


def layout():
    x = 0
    out = []
    for ch in TEXT:
        name = cmap[ord(ch)]
        out.append((name, x))
        x += hmtx[name][0]
    return out


def bounds(items):
    bp = BoundsPen(glyphs)
    for name, x in items:
        glyphs[name].draw(TransformPen(bp, (1, 0, 0, 1, x, 0)))
    return bp.bounds


items = layout()
x0, y0, x1, y1 = bounds(items)
for name, vw, vh, wdp, hdp in TARGETS:
    pad = vh * 0.12
    scale = min((vw - 2 * pad) / (x1 - x0), (vh - 2 * pad) / (y1 - y0))
    dx = (vw - (x1 - x0) * scale) / 2 - x0 * scale
    dy = (vh + (y1 - y0) * scale) / 2 + y0 * scale  # y flips: font y-up -> vector y-down
    pen = SVGPathPen(glyphs, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
    for g, x in items:
        glyphs[g].draw(TransformPen(pen, (scale, 0, 0, -scale, dx + x * scale, dy)))
    xml = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- NexaGram wordmark, generated by nexagram/tools/make_wordmark.py -->\n"
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{wdp}" '
        f'android:height="{hdp}" android:viewportWidth="{vw}" android:viewportHeight="{vh}">\n'
        f'    <path android:fillColor="#FFFFFFFF" android:pathData="{pen.getCommands()}" />\n'
        "</vector>\n"
    )
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".xml"), "w", encoding="utf-8") as f:
        f.write(xml)
    print(name, "ok")
